import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(root, "design/tokens.json");
const source = JSON.parse(await readFile(sourcePath, "utf8"));
const modes = source.meta.modes;

const HEADER = "// Generated by scripts/generate-tokens.mjs. Do not edit.\n";
const CSS_HEADER = "/* Generated by scripts/generate-tokens.mjs. Do not edit. */\n";

function upperSnake(value) {
  return value
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/[^A-Za-z0-9]+/g, "_")
    .toUpperCase();
}

function lowerSnake(value) {
  return value
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/[^A-Za-z0-9]+/g, "_")
    .toLowerCase();
}

function rustMode(mode) {
  return mode === "hc" ? "HighContrast" : mode[0].toUpperCase() + mode.slice(1);
}

function rustValue(token, mode) {
  const value = token.$value[mode];
  if (token.$type === "color") {
    if (typeof value === "string" && value.startsWith("system:")) return null;
    return JSON.stringify(value);
  }
  if (typeof value === "number") return `${value}_f32`;
  return null;
}

function generatedRust() {
  const grouped = new Map();
  for (const [key, token] of Object.entries(source.tokens)) {
    const [group, ...rest] = key.split(".");
    if (!grouped.has(group)) grouped.set(group, []);
    grouped.get(group).push([rest.join("."), token]);
  }

  const lines = [
    HEADER.trimEnd(),
    "",
    "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
    "pub enum Mode { Light, Dark, HighContrast }",
    "",
    "impl From<ditto_model::ThemeMode> for Mode {",
    "    fn from(value: ditto_model::ThemeMode) -> Self {",
    "        match value {",
    "            ditto_model::ThemeMode::Light => Self::Light,",
    "            ditto_model::ThemeMode::Dark => Self::Dark,",
    "            ditto_model::ThemeMode::HighContrast => Self::HighContrast,",
    "            ditto_model::ThemeMode::System => Self::Light,",
    "        }",
    "    }",
    "}",
    "",
    "pub fn parse_hex(value: &str) -> [u8; 4] {",
    "    let clean = value.strip_prefix('#').unwrap_or(value);",
    "    let parse = |start| u8::from_str_radix(&clean[start..start + 2], 16).unwrap_or(0);",
    "    match clean.len() {",
    "        6 => [parse(0), parse(2), parse(4), 255],",
    "        8 => [parse(0), parse(2), parse(4), parse(6)],",
    "        _ => [0, 0, 0, 255],",
    "    }",
    "}",
    "",
  ];

  for (const [group, entries] of grouped) {
    lines.push(`pub mod ${group} {`);
    for (const [name, token] of entries) {
      const ident = upperSnake(name);
      if (token.$type === "color") {
        for (const mode of modes) {
          const value = rustValue(token, mode);
          if (value !== null) {
            lines.push(`    pub const ${ident}_${upperSnake(mode)}: &str = ${value};`);
          }
        }
        lines.push(`    pub fn ${lowerSnake(name)}(mode: super::Mode) -> Option<&'static str> {`);
        lines.push("        match mode {");
        for (const mode of modes) {
          const value = rustValue(token, mode);
          lines.push(`            super::Mode::${rustMode(mode)} => ${value === null ? "None" : `Some(${value})`},`);
        }
        lines.push("        }");
        lines.push("    }");
      } else if (typeof token.$value.light === "number") {
        const values = modes
          .map((mode) => `super::Mode::${rustMode(mode)} => ${token.$value[mode]}_f32`)
          .join(", ");
        lines.push(`    pub fn ${lowerSnake(name)}(mode: super::Mode) -> f32 { match mode { ${values} } }`);
      } else if (token.$type === "fontFamily") {
        for (const mode of modes) {
          lines.push(`    pub const ${ident}_${upperSnake(mode)}: &[&str] = &[${token.$value[mode].map(JSON.stringify).join(", ")}];`);
        }
      } else if (token.$type === "shadow") {
        for (const mode of modes) {
          const value = token.$value[mode];
          const formatted =
            value === "none"
              ? "none"
              : `${value.x} ${value.y} ${value.blur} ${value.color}`;
          lines.push(`    pub const ${ident}_${upperSnake(mode)}: &str = ${JSON.stringify(formatted)};`);
        }
        lines.push(`    pub fn ${lowerSnake(name)}(mode: super::Mode) -> &'static str {`);
        lines.push("        match mode {");
        for (const mode of modes) {
          lines.push(
            `            super::Mode::${rustMode(mode)} => ${ident}_${upperSnake(mode)},`,
          );
        }
        lines.push("        }");
        lines.push("    }");
      } else if (token.$type === "cubicBezier") {
        for (const mode of modes) {
          lines.push(
            `    pub const ${ident}_${upperSnake(mode)}: [f32; 4] = [${token.$value[mode].map((value) => `${value}_f32`).join(", ")}];`,
          );
        }
        lines.push(`    pub fn ${lowerSnake(name)}(mode: super::Mode) -> [f32; 4] {`);
        lines.push("        match mode {");
        for (const mode of modes) {
          lines.push(
            `            super::Mode::${rustMode(mode)} => ${ident}_${upperSnake(mode)},`,
          );
        }
        lines.push("        }");
        lines.push("    }");
      }
    }
    lines.push("}", "");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

function cssColor(value) {
  if (typeof value !== "string") return value;
  if (!value.startsWith("system:")) return value;
  return {
    Window: "Canvas",
    ButtonFace: "ButtonFace",
    WindowText: "CanvasText",
    GrayText: "GrayText",
    Highlight: "Highlight",
    HighlightText: "HighlightText",
  }[value.slice("system:".length)] ?? value;
}

function generatedCss() {
  const labels = { light: "light", dark: "dark", hc: "hc" };
  const blocks = [];
  for (const mode of modes) {
    const lines = [];
    if (mode === "hc") lines.push("@media (forced-colors: active) {", "  :root {");
    else lines.push(`:root[data-theme="${labels[mode]}"] {`);
    for (const [key, token] of Object.entries(source.tokens)) {
      const value = token.$value[mode];
      if (typeof value !== "string" && typeof value !== "number") continue;
      const variable = `--ditto-${key.replace(/\./g, "-").replace(/[A-Z]/g, (char) => `-${char.toLowerCase()}`)}`;
      lines.push(`  ${variable}: ${token.$type === "color" ? cssColor(value) : value}${token.$type === "duration" ? "ms" : token.$type === "dimension" || token.$type === "fontSize" || token.$type === "lineHeight" || token.$type === "radius" ? "px" : ""};`);
    }
    if (mode === "hc") lines.push("  }", "}");
    else lines.push("}");
    blocks.push(lines.join("\n"));
  }
  return `${CSS_HEADER}${blocks.join("\n\n")}\n`;
}

function generatedTs() {
  return `${HEADER}export const tokens = ${JSON.stringify(source.tokens, null, 2)} as const;\nexport type TokenMode = "light" | "dark" | "hc";\n`;
}

const outputs = [
  ["crates/ditto-ui-tokens/src/lib.rs", generatedRust()],
  ["apps/ditto/ui/src/styles/tokens.generated.css", generatedCss()],
  ["apps/ditto/ui/src/tokens.generated.ts", generatedTs()],
];

for (const [relative, content] of outputs) {
  const target = resolve(root, relative);
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, content, "utf8");
}

execFileSync("cargo", ["fmt", "--all"], { cwd: root, stdio: "inherit" });
console.log(`Generated ${outputs.length} token files from design/tokens.json`);

